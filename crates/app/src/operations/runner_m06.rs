//! ⟨M06 W3 grant-path⟩ A grant on a remote runner waits for its issuer (ADR-0012 §4 item 2,
//! the ⟨2026-11-21⟩ bullets "How a grant comes to exist on a runner"; ADR-0005 §3.5 "Remote
//! reservations" condition 8).
//!
//! A runner never issues locally. An `ensure` on a runner, forwarded by a controller over
//! the management session or made locally, goes through the same admission as on any
//! installation: a covering standing policy, or `APPROVAL_REQUIRED` with a decision record
//! that is decided at the runner. What differs is the step after admission, for a grant
//! whose mechanism is `managed_certificate`:
//!
//! * **The grant is created `preparing` and waits.** Nothing is prepared, no attempt is
//!   recorded and no key is generated by the request. The operation stays `running` and
//!   answers `ACCEPTED`, naming the grant, so the controller that forwarded it can record
//!   what it asked for. The runner's own signer generates K_env only when the controller's
//!   host asks (`runner.prepare_remote_grant`), and the controller issues only for scope its
//!   own records authorize.
//! * **A grant no controller record covers stays pending** until its deadline. Its refresh
//!   dependency is the controller's issuer (`controller_dependency`).
//! * **When the certificates are installed** the runner runtime calls
//!   [`Operations::runner_grant_issued`]; every operation waiting on that grant is driven
//!   on, through the unchanged attempt, re-check and commit, with the runner's adapter for
//!   the mechanism (it materializes the binding from the runner's signer, never from an
//!   issuer here).
//!
//! Everything is keyed on [`RunnerGrants`] being set, which only a runner runtime does:
//! every other installation takes the paths it took before, byte for byte.

use std::sync::{Arc, PoisonError};

use heimdall_contract::Code;
use heimdall_contract::ids::{GrantId, OperationId};
use heimdall_contract::state::OperationState;

use super::{MANAGED_CERTIFICATE, Operations};
use crate::error::OpError;

/// The runner's own signer, as the `ensure` pipeline reads it (module docs).
pub trait RunnerGrants: Send + Sync {
    /// Whether the controller's issuer has issued for `grant`: the runner signer holds its
    /// K_env and a certificate for every pair of the grant.
    fn issued(&self, grant: &GrantId) -> bool;
}

impl Operations {
    /// Mark this installation's operations as a remote runner's, reading `grants` (module
    /// docs). Only a runner runtime calls it.
    pub fn set_runner_grants(&self, grants: Arc<dyn RunnerGrants>) {
        *self
            .inner
            .managed_ops
            .runner
            .write()
            .unwrap_or_else(PoisonError::into_inner) = Some(grants);
    }

    /// The runner's signer view; `None` on every installation that is not a runner.
    pub(super) fn runner_grants(&self) -> Option<Arc<dyn RunnerGrants>> {
        self.inner
            .managed_ops
            .runner
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// Whether `grant`, of `mechanism`, waits for its issuer here: this is a runner, the
    /// mechanism is `managed_certificate`, and the controller has not issued for it.
    pub(super) fn awaits_issuer(&self, mechanism: &str, grant: &GrantId) -> bool {
        mechanism == MANAGED_CERTIFICATE && self.runner_grants().is_some_and(|r| !r.issued(grant))
    }

    /// The answer of an operation whose grant waits for its issuer: `ACCEPTED`, naming the
    /// operation and the grant.
    pub(super) fn awaiting_issuer(operation: &OperationId, grant: &GrantId) -> OpError {
        OpError::new(
            Code::Accepted,
            "the grant is admitted and waits for its issuer (controller_dependency): a \
             runner never issues locally, and the controller issues only for scope its own \
             records authorize",
        )
        .with_operation(operation.clone())
        .with_resource("grant", Some(grant.to_string()))
    }

    /// The controller's issuer installed every certificate of `grant` (module docs): drive
    /// on each operation that waits on it. Each is led in its own task; nothing is waited
    /// for here. Returns how many were resumed.
    ///
    /// # Errors
    /// A store failure reading the open operations.
    pub async fn runner_grant_issued(&self, grant: &GrantId) -> Result<usize, OpError> {
        let gid = grant.clone();
        let waiting: Vec<OperationId> = self
            .local_write(move |tx, _| {
                let mut out = Vec::new();
                for op in tx.open_operations()? {
                    if op.state != OperationState::Running {
                        continue;
                    }
                    let on_grant = tx
                        .recovery_intent(&op.id)?
                        .and_then(|i| i.resolved)
                        .is_some_and(|r| r.grant.as_ref() == Some(&gid));
                    if on_grant {
                        out.push(op.id);
                    }
                }
                Ok(out)
            })
            .await?;
        for id in &waiting {
            let _ = self.lead_bounded(id, false, None).await;
        }
        Ok(waiting.len())
    }
}
