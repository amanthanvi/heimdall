/// The runner's own signer, as the `ensure` pipeline reads it (module docs).
pub trait RunnerGrants: Send + Sync {
    /// Whether the controller's issuer has issued for `grant`: the runner signer holds its
    /// K_env and a certificate for every pair of the grant.
    fn issued(&self, grant: &GrantId) -> bool;

    /// ⟨M06 W4⟩ Every grant the controller's issuer has issued for now ([`Self::issued`]),
    /// in ID order: what a local `ensure` may attach to (the attach rule, module docs).
    fn issued_grants(&self) -> Vec<GrantId> {
        Vec::new()
    }

    /// ⟨M06 W4⟩ Realize `binding`, a further binding on the issued grant `grant`, from
    /// the runner's signer: its own endpoint and files, listing that grant's certificates
    /// for `pairs` only, the binding's own subset of the grant's pairs, never the whole
    /// grant's (ADR-0012 §4 item 2 "Attach"). Synchronous file work.
    ///
    /// # Errors
    /// [`AdapterError`]; nothing of the binding is left behind.
    fn attach(
        &self,
        _binding: &BindingId,
        _grant: &GrantId,
        _pairs: &BTreeSet<AccessPair>,
    ) -> Result<EndpointRef, AdapterError> {
        Err(AdapterError::CapabilityUnavailable)
    }
}

/// ⟨M06 W4 grant-e2e; m06-plan §2 item 4 "The attach rule"; ADR-0012 §4 item 2
/// ⟨2026-11-21⟩ "A local `ensure` covered by a live issued grant attaches to it"⟩ The live
/// issued grant, among `issued`, that an `ensure` by `caller` for `pairs` of `profile`
/// (and, when known, with the deadline `deadline`) may attach to:
///
/// * **who:** only the runner's local owner, or the client that forwarded the `ensure`
///   the grant was admitted for (the grant's recorded caller is that paired client);
/// * **what:** the pairs are a subset of the grant's, for the grant's profile;
/// * **until:** the deadline is no later than the grant's.
///
/// The grant must be usable, managed, and not a delegated child. Attaching gives the
/// request a **new binding on the same grant**: nothing is admitted, prepared or issued
/// again. `None` when no grant qualifies (the request is then an ordinary new one).
///
/// # Errors
/// A store failure.
pub(super) fn covering_grant(
    tx: &mut Txn<'_>,
    issued: &[GrantId],
    caller: &CallerContext,
    profile: &ProfileId,
    pairs: &BTreeSet<AccessPair>,
    deadline: Option<Timestamp>,
) -> heimdall_store::Result<Option<GrantSnapshot>> {
    if pairs.is_empty() {
        return Ok(None);
    }
    for id in issued {
        let Some(g) = tx.grant(id)? else {
            continue;
        };
        if !g.state.permits_use()
            || g.parent.is_some()
            || !pairs.is_subset(&g.scope.pairs)
            || deadline.is_some_and(|d| d > g.deadline.effective)
        {
            continue;
        }
        let Some(origin) = tx.grant_origin(id)? else {
            continue;
        };
        if origin.profile != *profile || origin.mechanism != MANAGED_CERTIFICATE {
            continue;
        }
        let may_attach = match &caller.remote_client {
            None => caller.is_owner(),
            Some(client) => origin.caller.remote_client.as_ref() == Some(client),
        };
        if may_attach {
            return Ok(Some(g));
        }
    }
    Ok(None)
}

/// ⟨M06 W4⟩ The attach rule, in the transaction that resolved an operation's request as
/// allowed (as `stop_m05::reuse_in` for ruling I-1, which is tried first): when it is an
/// `ensure` on a runner that [`covering_grant`] finds a grant for, and that grant passes
/// the re-validation its new binding's activation will run, the intent pins the grant and
/// `Coalesce` and `Reconcile` are recorded as not attempted, so `Recheck` and `Commit` give
/// it a new binding on that grant. Returns whether it attached.
///
/// # Errors
/// A store failure.
#[allow(clippy::too_many_arguments)]
pub(super) fn attach_in(
    tx: &mut Txn<'_>,
    own: &EnvironmentId,
    adapters: &[AdapterInfo],
    op: &OperationRecord,
    kind: OperationKind,
    work: &WorkId,
    issued: &[GrantId],
    now: Timestamp,
) -> heimdall_store::Result<bool> {
    if kind != OperationKind::Ensure || issued.is_empty() {
        return Ok(false);
    }
    let Some(mut intent) = tx.recovery_intent(&op.id)? else {
        return Ok(false);
    };
    let Some(resolved) = intent.resolved.clone().filter(|r| r.grant.is_none()) else {
        return Ok(false);
    };
    if resolved
        .adapter
        .as_ref()
        .is_none_or(|a| a.mechanism != MANAGED_CERTIFICATE)
        || resolved.workspace.is_some()
    {
        return Ok(false);
    }
    let Some(g) = covering_grant(
        tx,
        issued,
        &op.key.caller,
        &resolved.profile,
        &resolved.scope.pairs,
        Some(resolved.deadline.effective),
    )?
    else {
        return Ok(false);
    };
    if g.environment != op.environment
        || !resolved.scope.capabilities.is_subset(&g.scope.capabilities)
    {
        return Ok(false);
    }
    let probe = ResolvedIntent {
        grant: Some(g.id.clone()),
        ..resolved
    };
    if activation_refusal(
        tx,
        own,
        adapters,
        &probe,
        &g,
        now,
        Activation::NewBinding,
        Some((&op.environment, work)),
        None,
    )?
    .is_some()
    {
        return Ok(false);
    }
    if let Some(r) = intent.resolved.as_mut() {
        r.grant = Some(g.id);
    }
    tx.set_recovery_intent(&op.id, &intent)?;
    for stage in [EnsureStage::Coalesce, EnsureStage::Reconcile] {
        tx.append_stage_receipt(&op.id, &receipt(stage, now, EffectReceipt::NotAttempted))?;
    }
    Ok(true)
}

impl Operations {
    /// Mark this installation's operations as a remote runner's, reading `grants` (module
    /// docs). Only a runner runtime calls it.
    pub fn set_runner_grants(&self, grants: Arc<dyn RunnerGrants>) {
        *self
            .inner
            .managed_ops
            .runner
            .write()
            .unwrap_or_else(PoisonError::into_inner) = Some(grants);
    }

    /// The runner's signer view; `None` on every installation that is not a runner.
    pub(super) fn runner_grants(&self) -> Option<Arc<dyn RunnerGrants>> {
        self.inner
            .managed_ops
            .runner
            .read()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// Whether `grant`, of `mechanism`, waits for its issuer here: this is a runner, the
    /// mechanism is `managed_certificate`, and the controller has not issued for it.
    pub(super) fn awaits_issuer(&self, mechanism: &str, grant: &GrantId) -> bool {
        mechanism == MANAGED_CERTIFICATE && self.runner_grants().is_some_and(|r| !r.issued(grant))
    }

    /// The answer of an operation whose grant waits for its issuer: `ACCEPTED`, naming the
    /// operation and the grant.
    pub(super) fn awaiting_issuer(operation: &OperationId, grant: &GrantId) -> OpError {
        OpError::new(
            Code::Accepted,
            "the grant is admitted and waits for its issuer (controller_dependency): a \
             runner never issues locally, and the controller issues only for scope its own \
             records authorize",
        )
        .with_operation(operation.clone())
        .with_resource("grant", Some(grant.to_string()))
    }

    /// ⟨M06 W4⟩ The grant the open operation `operation` waits on its issuer for: this is a
    /// runner, the operation is `running`, and its resolved grant is a managed one the
    /// controller has not issued for. `None` otherwise (and on a store failure).
    pub async fn awaiting_issuer_grant(&self, operation: &OperationId) -> Option<GrantId> {
        self.runner_grants()?;
        let op = operation.clone();
        let (grant, mechanism) = self
            .local_write(move |tx, _| {
                let Some(record) = tx.operation(&op)? else {
                    return Ok(None);
                };
                if record.state != OperationState::Running {
                    return Ok(None);
                }
                Ok(tx
                    .recovery_intent(&op)?
                    .and_then(|i| i.resolved)
                    .and_then(|r| Some((r.grant?, r.adapter?.mechanism))))
            })
            .await
            .ok()
            .flatten()?;
        self.awaits_issuer(&mechanism, &grant).then_some(grant)
    }

    /// The controller's issuer installed every certificate of `grant` (module docs): drive
    /// on each operation that waits on it. Each is led in its own task; nothing is waited
    /// for here. Returns how many were resumed.
    ///
    /// # Errors
    /// A store failure reading the open operations.
    pub async fn runner_grant_issued(&self, grant: &GrantId) -> Result<usize, OpError> {
        let gid = grant.clone();
        // ⟨M06 W4⟩ The grant's signing gate (ADR-0008 D2 item 3a). A local managed grant
        // gets it with its credential instance; a runner records none, so it is created
        // here, once, when the controller's certificates are installed: a signature for
        // the runner's K_env is admitted only under it, and a narrowing (a delivered
        // revoke) takes it exclusively, so nothing is signed while one is applied. It
        // stays until the process ends; it authorizes nothing by itself (every signature
        // is still read against the store and the runner's signer).
        let gates = self.signing_gates().clone();
        let gated = grant.clone();
        self.local_write(move |tx, _| {
            if !gates.contains(&gated)
                && let Some(g) = tx.grant(&gated)?
            {
                let ancestors = super::managed_driver_m03::ancestors_root_first(tx, &g)?;
                gates.retain(&gated, &ancestors);
            }
            Ok(())
        })
        .await?;
        let waiting: Vec<OperationId> = self
            .local_write(move |tx, _| {
                let mut out = Vec::new();
                for op in tx.open_operations()? {
                    if op.state != OperationState::Running {
                        continue;
                    }
                    let on_grant = tx
                        .recovery_intent(&op.id)?
                        .and_then(|i| i.resolved)
                        .is_some_and(|r| r.grant.as_ref() == Some(&gid));
                    if on_grant {
                        out.push(op.id);
                    }
                }
                Ok(out)
            })
            .await?;
        for id in &waiting {
            let _ = self.lead_bounded(id, false, None).await;
        }
        Ok(waiting.len())
    }
}
