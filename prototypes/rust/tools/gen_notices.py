#!/usr/bin/env python3
"""Write dist/THIRD-PARTY-NOTICES.txt: license and notice texts for everything
statically linked into the four artifacts (round 2; the round-1 review found that dist/
shipped no notices). Identical texts are printed once, with the components that use them.

Usage (from prototypes/rust; build.sh calls it): python3 tools/gen_notices.py <out-file>
Local sources only; see tools/inventory.py.
"""
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import inventory as inv  # noqa: E402


def main():
    out_path = sys.argv[1]
    texts = {}   # sha256 -> (text, [component labels])
    rows = []    # (section, label, license, [text sha])

    def add(section, label, lic, files):
        shas = []
        for f in files:
            try:
                t = open(f, encoding="utf-8", errors="replace").read()
            except OSError:
                continue
            h = hashlib.sha256(t.encode()).hexdigest()
            texts.setdefault(h, (t, os.path.basename(f), []))[2].append(label)
            shas.append(h[:12])
        rows.append((section, label, lic, shas))

    dirs = inv.crate_dirs()
    for pkg, e in sorted(inv.crates().items(), key=lambda kv: kv[0].lower()):
        if "linked" not in e["kind"]:
            continue
        tg = "all targets" if len(e["targets"]) == len(inv.TARGETS) else ", ".join(sorted(e["targets"]))
        files = inv.license_files(dirs.get(pkg))
        label = f"{pkg} ({tg})"
        if not files:  # e.g. winapi-x86_64-pc-windows-gnu ships no license file
            files, label = inv.rust_license_texts()[:2], label + " [crate ships no license file; generic texts]"
        add("crates.io crates linked into the artifacts", label, e["license"], files)
    rust = inv.rust_license_texts()
    for name, ver, lic, d in inv.std_crates():
        files = inv.license_files(d) or rust
        tg = "windows-x64" if name in inv.STD_WINDOWS_ONLY else "all targets"
        add("Rust standard library (rustc " + ver_of_rustc() + ")", f"{name} {ver} ({tg})", lic, files)
    for c in inv.native_components():
        add("Native runtime components", f'{c["component"]} [{c["targets"]}]', c["license"], c["texts"])

    w = []
    w.append("THIRD-PARTY NOTICES: heimdall-proto (Rust + Ratatui G02 prototype, disposable)\n")
    w.append("Generated by prototypes/rust/tools/gen_notices.py from local sources: cargo tree/metadata\n"
             "(crate source directories), the rust-src component and share/doc/rust of the toolchain\n"
             "that built the artifacts, and the license files of the zig installation used as linker.\n"
             "Covers every target in dist/; the per-target column says where a component is linked.\n"
             "Declared licenses are the crates' own `license` fields; texts are the files each\n"
             "component ships. The project's own license is still a placeholder (spec 15.3 open).\n\n")
    section = None
    for sec, label, lic, shas in rows:
        if sec != section:
            w.append("=" * 78 + "\n" + sec + "\n" + "=" * 78 + "\n")
            section = sec
        w.append(f"- {label}\n    license: {lic}\n    texts: {', '.join(shas) if shas else '(none shipped by the component)'}\n")
    w.append("\n" + "=" * 78 + "\nLicense and notice texts (by text id)\n" + "=" * 78 + "\n")
    for h, (t, fname, users) in sorted(texts.items(), key=lambda kv: kv[1][1]):
        w.append(f"\n----- text {h[:12]} ({fname}); used by {len(users)} component(s) -----\n")
        w.append(t if t.endswith("\n") else t + "\n")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("".join(w))
    print(f"{out_path}: {len(rows)} components, {len(texts)} distinct texts")


def ver_of_rustc():
    return inv.run(["rustc", "--version"]).split()[1]


if __name__ == "__main__":
    main()
