#!/usr/bin/env python3
"""Generate LICENSES.md: crates (cargo tree), the Rust standard library and its vendored
dependencies (rust-src), and native runtime components (link line + zig) that end up in
the four artifacts. Round 2 added the last two sections (round-1 review: notice inventory
incomplete). Full texts: dist/THIRD-PARTY-NOTICES.txt (tools/gen_notices.py).

Run from prototypes/rust: python3 tools/gen_licenses.py > LICENSES.md
Local sources only (cargo --offline, rust-src component, zig installation).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import inventory as inv  # noqa: E402


def main():
    cargo_v = inv.run(["cargo", "-V"]).strip()
    rustc_v = inv.run(["rustc", "--version"]).strip()
    allpk = inv.crates()
    licenses = {}
    for p, e in allpk.items():
        licenses.setdefault(e["license"] or "(none declared)", []).append(p)
    w = sys.stdout.write
    w("# Dependency licenses: Rust G02 prototype\n\n")
    w("Generated by `prototypes/rust/tools/gen_licenses.py`. Three parts: (1) crates.io crates from "
      f"`cargo tree --locked --offline -e normal,build --target <triple> --format '{{p}}|{{l}}'` ({cargo_v}); "
      f"(2) the Rust standard library and the crates it vendors, from the `rust-src` component of {rustc_v}; "
      "(3) native runtime components from the linker inputs rustc passes (observed with `--print=link-args`) "
      "and markers in the artifacts. License columns are the declared `license` fields (not cross-checked "
      "against LICENSE files). The texts themselves ship as `dist/THIRD-PARTY-NOTICES.txt`. Dev-dependencies: none.\n\n")
    w(f"Total distinct crates.io crate versions (all four targets, linked + build-time): {len(allpk)}\n\n")
    w("## 1. crates.io crates\n\n### License summary\n\n| Declared license | Crates |\n|---|---|\n")
    for lic, pkgs in sorted(licenses.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        w(f"| `{lic}` | {len(pkgs)} |\n")
    w("\n### Crates\n\n| Crate | Declared license | Use | Targets |\n|---|---|---|---|\n")
    for p in sorted(allpk, key=lambda s: (s.split(' ')[0].lower(), s)):
        e = allpk[p]
        tg = "all" if len(e["targets"]) == len(inv.TARGETS) else ", ".join(sorted(e["targets"]))
        w(f"| {p} | `{e['license']}` | {', '.join(sorted(e['kind']))} | {tg} |\n")
    w("\n## 2. Rust standard library (statically linked into every artifact)\n\n"
      "std is built from these crates for the four targets (library/std/Cargo.toml dependency set; "
      "versions from library/Cargo.lock). Version 0.0.0 marks in-tree library crates. "
      "Panic-location strings `/rust/deps/<crate>-<version>` in the artifacts confirm at least "
      "addr2line, gimli and rustc-demangle on every Unix target and miniz_oxide on Linux "
      "(observed in round 1 and round 2 artifacts).\n\n"
      "| Crate | Version | Declared license | Targets |\n|---|---|---|---|\n")
    for name, ver, lic, _d in inv.std_crates():
        tg = "windows-x64" if name in inv.STD_WINDOWS_ONLY else "all"
        w(f"| {name} | {ver} | `{lic}` | {tg} |\n")
    w("\n## 3. Native runtime components\n\n| Component | Targets | License | Evidence |\n|---|---|---|---|\n")
    for c in inv.native_components():
        w(f"| {c['component']} | {c['targets']} | {c['license']} | {c['evidence']} |\n")
    w("\nWhich exact object files the zig linker wrapper substitutes for rustc's self-contained musl and "
      "mingw inputs was not traced object by object; the evidence column says what was observed.\n")


if __name__ == "__main__":
    main()
