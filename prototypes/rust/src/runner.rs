//! `run`: launch argv without a shell, forward signals, map status (contract §4).
//!
//! Unix (round 2, contract §9.1 K6a): exec semantics. The child stays in
//! heimdall-proto's process group and session and never receives the terminal
//! foreground: heimdall-proto does not call `setpgid`, `tcsetpgrp` or stop anything,
//! so pipeline peers and a script that started it as an `&` job keep their terminal
//! access, and job control (Ctrl-Z, `fg`, `bg`, `killpg`) treats heimdall-proto and
//! the child as one job.
//!
//! * A forwarded signal (INT, TERM, HUP, QUIT, WINCH) whose disposition was inherited
//!   as `SIG_IGN` gets no handler, so `execve` keeps it ignored in the child and it is
//!   never forwarded.
//! * Every other forwarded signal is caught with its `siginfo` (signal-hook
//!   `WithRawSiginfo`, no C code) and sent to the child's PID with `kill(2)`, unless
//!   the child already received the same signal from the kernel:
//!   - Linux: a signal generated by the terminal driver carries `si_code == SI_KERNEL`
//!     (> 0); `kill`, `sigqueue` and `tgkill` carry `si_code <= 0`. Terminal INT, QUIT
//!     and WINCH go to the foreground process group, which contains the child, so they
//!     are not forwarded. A kernel SIGHUP from a hangup goes only to the session
//!     leader; it is forwarded when heimdall-proto is the session leader.
//!   - Other Unix (macOS): the kernel reports the same `siginfo` for a terminal
//!     signal and for `kill(2)` (observed on macOS 27: `si_code == 0` and `si_pid` =
//!     the process that wrote to the pty master, in both cases), so the two cannot be
//!     told apart. Every received signal is forwarded. Consequence (documented
//!     limitation, REPORT.md round 2): with a terminal, Ctrl-C, Ctrl-\ and resize reach
//!     the child twice on macOS.
//! * A signal sent to the whole process group by another process (`killpg`) reaches
//!   the child directly and is forwarded as well (`si_code` is SI_USER): the child sees
//!   it twice on every platform. The contract governs only terminal-generated and
//!   PID-directed signals.
//! * The child is reaped only after the forwarder is disarmed (`waitid(WNOWAIT)`), so
//!   a forwarded signal can never hit a recycled PID.
//! * Known stack limitation: Rust std sets SIGPIPE to `SIG_IGN` before `main` and
//!   resets it to `SIG_DFL` in every spawned child; stable Rust has no opt-out
//!   (`-Zon-broken-pipe=inherit` is nightly-only). An inherited ignored SIGPIPE is
//!   therefore not preserved in the child.
//!
//! Windows (compile-checked only): `std::process::Command` builds the command line
//! with std's CommandLineToArgvW-compatible quoting (and refuses unsafe .bat/.cmd
//! arguments since Rust 1.77.2); console Ctrl-C reaches the child directly because it
//! shares the console, so the parent installs a no-op handler and keeps waiting.

use std::ffi::OsString;

use serde_json::json;

use crate::envelope::{Code, Envelope, State};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RunOutcome {
    pub launched: bool,
    pub exit_code: Option<i32>,
    pub signal: Option<i32>,
    /// Exit status heimdall-proto itself should use.
    pub process_exit: i32,
    /// Human diagnostic for stderr (launch failures only).
    pub diagnostic: Option<String>,
}

impl RunOutcome {
    /// Side-channel result for `--meta-file`.
    pub fn meta_envelope(&self) -> Envelope {
        let data =
            json!({"launched": self.launched, "exit_code": self.exit_code, "signal": self.signal});
        if self.launched {
            Envelope {
                state: State::Succeeded,
                code: Code::ChildExited,
                data,
                warnings: vec![],
            }
        } else {
            Envelope {
                state: State::Failed,
                code: Code::ChildLaunchFailed,
                data,
                warnings: vec![],
            }
        }
    }

    fn launch_failed(e: &std::io::Error) -> Self {
        RunOutcome {
            launched: false,
            exit_code: None,
            signal: None,
            process_exit: 127,
            diagnostic: Some(format!(
                "heimdall-proto: cannot launch command: {:?}",
                e.kind()
            )),
        }
    }

    #[cfg(unix)]
    fn internal(msg: String) -> Self {
        RunOutcome {
            launched: false,
            exit_code: None,
            signal: None,
            process_exit: 1,
            diagnostic: Some(msg),
        }
    }

    fn from_wait(status: std::io::Result<std::process::ExitStatus>) -> Self {
        match status {
            Ok(st) => {
                let (exit_code, signal, process_exit) = map_status(st);
                RunOutcome {
                    launched: true,
                    exit_code,
                    signal,
                    process_exit,
                    diagnostic: None,
                }
            }
            Err(e) => RunOutcome {
                launched: true,
                exit_code: None,
                signal: None,
                process_exit: 1,
                diagnostic: Some(format!("heimdall-proto: wait failed: {:?}", e.kind())),
            },
        }
    }
}

/// Map a terminated child's status to (exit_code, signal, process_exit).
#[cfg(unix)]
pub fn map_status(st: std::process::ExitStatus) -> (Option<i32>, Option<i32>, i32) {
    use std::os::unix::process::ExitStatusExt;
    if let Some(c) = st.code() {
        (Some(c), None, c)
    } else if let Some(s) = st.signal() {
        (None, Some(s), 128 + s)
    } else {
        (None, None, 1)
    }
}

#[cfg(windows)]
pub fn map_status(st: std::process::ExitStatus) -> (Option<i32>, Option<i32>, i32) {
    let c = st.code().unwrap_or(1);
    (Some(c), None, c)
}

/// Should a caught signal be forwarded to the child? See the module docs.
#[cfg(unix)]
fn should_forward(info: &libc::siginfo_t) -> bool {
    #[cfg(any(target_os = "linux", target_os = "android"))]
    {
        // si_code > 0 (SI_KERNEL): generated by the kernel (terminal driver, hangup).
        if info.si_code > 0 {
            let leader = rustix::process::getsid(None).ok() == Some(rustix::process::getpid());
            return info.si_signo == libc::SIGHUP && leader;
        }
        true
    }
    #[cfg(not(any(target_os = "linux", target_os = "android")))]
    {
        let _ = info;
        true
    }
}

#[cfg(unix)]
pub fn run(argv: &[OsString]) -> RunOutcome {
    use rustix::io::Errno;
    use rustix::process::{Pid, Signal, WaitId, WaitIdOptions, kill_process, waitid};
    use signal_hook::iterator::SignalsInfo;
    use signal_hook::iterator::exfiltrator::WithRawSiginfo;
    use std::process::Command;
    use std::sync::{Arc, Mutex};

    // K6a: leave inherited-ignored signals alone (execve keeps SIG_IGN in the child).
    let caught: Vec<i32> = crate::sigdisp::HANDLED
        .iter()
        .filter(|s| !crate::sigdisp::inherited_ignored(**s))
        .map(|s| *s as i32)
        .collect();
    // Register before spawning so no signal in the spawn window terminates us and
    // orphans the child; caught signals are buffered and forwarded once the
    // forwarding thread starts.
    let mut signals = match SignalsInfo::<WithRawSiginfo>::new(&caught) {
        Ok(s) => s,
        Err(e) => {
            crate::sigdisp::restore_mask();
            return RunOutcome::internal(format!(
                "heimdall-proto: cannot install signal handlers: {:?}",
                e.kind()
            ));
        }
    };
    let handle = signals.handle();

    // Round 3b (review2 defect 1, §4 "does not exit first"): the forwarding thread is
    // started BEFORE the child, with `Builder::spawn` (which reports failure instead of
    // panicking). If no thread can be created (pids cgroup, RLIMIT_NPROC, a huge
    // RUST_MIN_STACK) nothing has been launched yet, so the failure is reported without
    // leaving an orphan behind. The thread learns the child's PID through a channel;
    // signals caught before that stay buffered in `signals` and are forwarded once.
    let (pid_tx, pid_rx) = std::sync::mpsc::channel::<Pid>();
    let exited = Arc::new(Mutex::new(false));
    let exited_fwd = Arc::clone(&exited);
    let forwarder = match std::thread::Builder::new()
        .name("hp-signal-forwarder".into())
        .spawn(move || {
            let Ok(pid) = pid_rx.recv() else {
                return; // launch failed: nothing to forward to
            };
            for info in signals.forever() {
                if !should_forward(&info) {
                    continue;
                }
                let guard = exited_fwd.lock().unwrap_or_else(|p| p.into_inner());
                if !*guard && let Some(sig) = Signal::from_named_raw(info.si_signo) {
                    let _ = kill_process(pid, sig);
                }
            }
        }) {
        Ok(t) => t,
        Err(e) => {
            handle.close();
            crate::sigdisp::restore_mask();
            return RunOutcome::internal(format!(
                "heimdall-proto: cannot start the signal forwarder, command not launched: {:?}",
                e.kind()
            ));
        }
    };
    // Handlers are in place: let signals blocked since main() through.
    crate::sigdisp::restore_mask();

    let mut child = match Command::new(&argv[0]).args(&argv[1..]).spawn() {
        Ok(c) => c,
        Err(e) => {
            drop(pid_tx);
            handle.close();
            let _ = forwarder.join();
            return RunOutcome::launch_failed(&e);
        }
    };
    let pid = Pid::from_child(&child);
    let _ = pid_tx.send(pid);

    // Wait for termination without reaping, so the PID stays valid while the
    // forwarder may still signal it.
    loop {
        match waitid(
            WaitId::Pid(pid),
            WaitIdOptions::EXITED | WaitIdOptions::NOWAIT,
        ) {
            Ok(Some(_)) => break,
            Ok(None) => continue,
            Err(Errno::INTR) => continue,
            Err(_) => break, // fall through to std's wait, which reports the error
        }
    }
    *exited.lock().unwrap_or_else(|p| p.into_inner()) = true;
    let status = child.wait();
    handle.close();
    let _ = forwarder.join();
    RunOutcome::from_wait(status)
}

#[cfg(windows)]
pub fn run(argv: &[OsString]) -> RunOutcome {
    use std::process::Command;
    // Console Ctrl-C/Ctrl-Break are delivered to every process attached to the
    // console, including the child; the parent ignores them and keeps waiting.
    let _ = ctrlc::set_handler(|| {});
    match Command::new(&argv[0]).args(&argv[1..]).spawn() {
        Ok(mut child) => RunOutcome::from_wait(child.wait()),
        Err(e) => RunOutcome::launch_failed(&e),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn meta_shapes() {
        let o = RunOutcome {
            launched: false,
            exit_code: None,
            signal: None,
            process_exit: 127,
            diagnostic: None,
        };
        let v = o.meta_envelope().to_value();
        assert_eq!(v["code"], "CHILD_LAUNCH_FAILED");
        assert_eq!(v["state"], "failed", "K5");
        assert_eq!(
            v["data"],
            json!({"launched": false, "exit_code": null, "signal": null})
        );
        let o = RunOutcome {
            launched: true,
            exit_code: None,
            signal: Some(15),
            process_exit: 143,
            diagnostic: None,
        };
        let v = o.meta_envelope().to_value();
        assert_eq!(v["code"], "CHILD_EXITED");
        assert_eq!(v["state"], "succeeded", "K5: whatever the child status");
        assert_eq!(v["data"]["signal"], 15);
    }

    #[cfg(unix)]
    #[test]
    fn launch_failure_is_127() {
        let o = run(&[OsString::from("heimdall-proto-definitely-not-on-path-ü")]);
        assert!(!o.launched);
        assert_eq!(o.process_exit, 127);
    }

    #[cfg(unix)]
    #[test]
    fn exit_code_and_signal_mapping() {
        let o = run(&["sh".into(), "-c".into(), "exit 42".into()]);
        assert_eq!(
            (o.launched, o.exit_code, o.signal, o.process_exit),
            (true, Some(42), None, 42)
        );
        let o = run(&["sh".into(), "-c".into(), "kill -TERM $$".into()]);
        assert_eq!(
            (o.exit_code, o.signal, o.process_exit),
            (None, Some(15), 143)
        );
    }
}
