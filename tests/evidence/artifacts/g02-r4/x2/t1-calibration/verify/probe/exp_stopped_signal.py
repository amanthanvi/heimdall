#!/usr/bin/env python3
"""Kernel-semantics side experiment for the verify task: what happens to a *stopped*
process (own process group) that receives SIGINT / SIGQUIT / SIGTERM, either by kill(2)
or generated by its controlling terminal (^C, ^\\ typed on a pty while the stopped
process's group is the foreground group)?  Prints one JSON line per case.  Only
processes started here are signalled, by exact PID."""
import json, os, pty, signal, sys, time, subprocess, termios

IS_DARWIN = sys.platform == "darwin"


def state(pid):
    if IS_DARWIN:
        out = subprocess.run(["ps", "-o", "stat=", "-p", str(pid)], capture_output=True, text=True).stdout.strip()
        return out or None
    try:
        s = open(f"/proc/{pid}/stat").read()
    except (FileNotFoundError, ProcessLookupError):
        return None
    return s[s.rindex(")") + 2:].split()[0]


def reap(pid):
    try:
        p, st = os.waitpid(pid, os.WNOHANG)
        return None if p == 0 else st
    except ChildProcessError:
        return "nochild"


def finish(pid):
    """Kill the experiment's own child by exact PID and reap it."""
    try:
        os.kill(pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        os.waitpid(pid, 0)
    except ChildProcessError:
        pass


def case_kill(stop_sig, then_sig):
    pid = os.fork()
    if pid == 0:
        os.setpgid(0, 0)
        os.execvp("sleep", ["sleep", "30"])
    time.sleep(0.2)
    os.kill(pid, stop_sig)
    time.sleep(0.3)
    s_stopped = state(pid)
    os.kill(pid, then_sig)
    time.sleep(0.5)
    s_after = state(pid); w_after = reap(pid)
    os.kill(pid, signal.SIGCONT) if w_after is None else None
    time.sleep(0.5)
    s_cont = state(pid); w_cont = reap(pid)
    rec = {"case": "kill", "stop": stop_sig.name, "then": then_sig.name, "state_stopped": s_stopped,
           "state_after_signal": s_after, "wait_after_signal": w_after,
           "state_after_CONT": s_cont, "wait_after_CONT": w_cont}
    finish(pid)
    return rec


def case_tty(stop_sig, key, name):
    """sleep 30 as the foreground group of a fresh pty (session leader), stopped by
    kill(2) with stop_sig, then `key` written to the pty master."""
    pid, fd = pty.fork()
    if pid == 0:
        os.execvp("sleep", ["sleep", "30"])
    time.sleep(0.2)
    attrs = termios.tcgetattr(fd)
    isig = bool(attrs[3] & termios.ISIG)
    os.kill(pid, stop_sig)
    time.sleep(0.3)
    s_stopped = state(pid)
    os.write(fd, key)
    time.sleep(0.5)
    s_after = state(pid); w_after = reap(pid)
    if w_after is None:
        os.kill(pid, signal.SIGCONT)
    time.sleep(0.5)
    s_cont = state(pid); w_cont = reap(pid)
    rec = {"case": "tty", "stop": stop_sig.name, "then": name, "isig": isig, "state_stopped": s_stopped,
           "state_after_key": s_after, "wait_after_key": w_after,
           "state_after_CONT": s_cont, "wait_after_CONT": w_cont}
    finish(pid)
    os.close(fd)
    return rec


def main():
    out = []
    for stop in (signal.SIGTSTP, signal.SIGSTOP):
        for then in (signal.SIGINT, signal.SIGQUIT, signal.SIGTERM):
            out.append(case_kill(stop, then))
        out.append(case_tty(stop, b"\x03", "^C"))
        out.append(case_tty(stop, b"\x1c", "^\\"))
    for r in out:
        print(json.dumps({"platform": sys.platform, **r}))


if __name__ == "__main__":
    main()
